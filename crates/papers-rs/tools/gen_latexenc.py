#!/usr/bin/env python3
"""Generate src/bib/latexenc_tables.rs from the published character table of the papers
specification, data/latex-characters.tsv (design/data/latex-characters.tsv of papers,
bibtex.md 4.1 and 4.2): the `encode` rows are `unicode_to_latex`, the `accented` rows other
spellings of accented letters. The table is the contract: no dependency on papers.

    python3 tools/gen_latexenc.py > src/bib/latexenc_tables.rs

To follow a newer papers, copy the tables from its repository first (`git show
<commit>:design/data/<name>` into data/), data/ascii-transliteration.tsv too (the tests of the
transliteration read it).
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
TSV = os.path.join(HERE, '..', 'data', 'latex-characters.tsv')


def lit(s, quote='"'):
    "a Rust literal of a text (or of a character, with quote `'`)"
    out = []
    for ch in s:
        o = ord(ch)
        if ch == '\\' or ch == quote:
            out.append('\\' + ch)
        elif 0x20 <= o < 0x7f:
            out.append(ch)
        else:
            out.append('\\u{%x}' % o)
    return quote + ''.join(out) + quote


def rows():
    "the (kind, character, LaTeX text) of the table, in its order"
    with open(TSV, encoding='utf-8', newline='') as f:
        lines = f.read().split('\n')
    assert lines[-1] == '', 'the table ends with a newline'
    lines = [line for line in lines[:-1] if not line.startswith('#')]
    assert lines[0] == 'code\tkind\tlatex'
    for line in lines[1:]:
        # the LaTeX text has no tab and no escape; a trailing space is part of it
        code, kind, latex = line.split('\t')
        assert code.startswith('U+') and kind in ('encode', 'accented'), line
        yield kind, chr(int(code[2:], 16)), latex


def table(name, doc, pairs):
    print(f'/// {doc}')
    print(f'pub(super) static {name}: &[(char, &str)] = &[')
    for char, latex in pairs:
        print(f'    ({lit(char, chr(39))}, {lit(latex)}),')
    print('];')
    print()


table_rows = list(rows())
print('// Generated by tools/gen_latexenc.py from data/latex-characters.tsv; do not edit.')
print()
table('UNICODE_TO_LATEX', '`unicode_to_latex`: (character, LaTeX), in the order of the table.',
      [(c, t) for k, c, t in table_rows if k == 'encode'])
table('ACCENTED_LATEX', 'Other spellings of accented letters (`unicode_to_crappy_latex1`), in the order of the table.',
      [(c, t) for k, c, t in table_rows if k == 'accented'])
