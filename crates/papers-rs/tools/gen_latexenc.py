#!/usr/bin/env python3
"""Generate src/bib/latexenc_tables.rs from the tables of papers.latexenc
(the vendored bibserver module: unicode_to_latex, unicode_to_crappy_latex1,
unicode_to_crappy_latex2). Run with the python that has papers installed:

    python3 tools/gen_latexenc.py > src/bib/latexenc_tables.rs
"""
import sys

import papers.latexenc as L


def lit(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch == '\\':
            out.append('\\\\')
        elif ch == '"':
            out.append('\\"')
        elif 0x20 <= o < 0x7f:
            out.append(ch)
        else:
            assert not (0xD800 <= o <= 0xDFFF), 'lone surrogate in a table'
            out.append('\\u{%x}' % o)
    return '"' + ''.join(out) + '"'


def table(name, doc, pairs):
    print(f'/// {doc}')
    print(f'pub(super) static {name}: &[(&str, &str)] = &[')
    for k, v in pairs:
        print(f'    ({lit(k)}, {lit(v)}),')
    print('];')
    print()


print('// Generated by tools/gen_latexenc.py from papers.latexenc; do not edit.')
print()
table('UNICODE_TO_LATEX', '`unicode_to_latex`: (unicode, latex), in the order of the module.', L.unicode_to_latex)
table('UNICODE_TO_CRAPPY_LATEX1', '`unicode_to_crappy_latex1`', L.unicode_to_crappy_latex1)
table('UNICODE_TO_CRAPPY_LATEX2', '`unicode_to_crappy_latex2`', L.unicode_to_crappy_latex2)
