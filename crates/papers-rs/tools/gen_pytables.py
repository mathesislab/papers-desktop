#!/usr/bin/env python3
"""Generate src/pytables.rs: the Python 3 data that papers' names depend on
(the HTML entities of `slugify`, the Unicode digits of `\\d` and `str.isdigit`).

    python3 tools/gen_pytables.py > src/pytables.rs
"""
import sys
import unicodedata
from html.entities import name2codepoint


def ranges(test):
    out, start = [], None
    for cp in range(0x110000):
        if test(chr(cp)):
            if start is None:
                start = cp
            last = cp
        elif start is not None:
            out.append((start, last))
            start = None
    if start is not None:
        out.append((start, last))
    return out


def table(name, doc, items):
    print(f'/// {doc}')
    print(f'pub(crate) static {name}: &[(u32, u32)] = &[')
    for a, b in items:
        print(f'    (0x{a:x}, 0x{b:x}),')
    print('];\n')


print(f'// Generated by tools/gen_pytables.py (Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}); do not edit.\n')
print('/// `html.entities.name2codepoint`, sorted by name.')
print('pub(crate) static ENTITIES: &[(&str, u32)] = &[')
for name, cp in sorted(name2codepoint.items()):
    print(f'    ("{name}", {cp}),')
print('];\n')
table('DECIMAL', 'The characters of `str.isdecimal()` (category Nd: `\\d` of `re`), as ranges.',
      ranges(lambda c: c.isdecimal()))
table('DIGIT', 'The characters of `str.isdigit()`, as ranges.', ranges(lambda c: c.isdigit()))
table('ALNUM', 'The characters of `str.isalnum()` (`\\w` of `re` is these and `_`), as ranges.',
      ranges(lambda c: c.isalnum()))
