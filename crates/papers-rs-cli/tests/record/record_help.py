#!/usr/bin/env python3
"""Record the usage and the help of every command of papers-cli (the reference)
into crates/papers-rs-cli/src/help_text.rs.

    python3 record_help.py [PAPERS]

PAPERS is the papers executable (default: papers in the PATH). The help is that
of a run outside of any library, with an empty global configuration (HOME
is a directory that does not exist): the defaults shown in it are the built-in ones.
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile

PAPERS = sys.argv[1] if len(sys.argv) > 1 else 'papers'
# a home directory that does not exist: the help shows the paths under it
HOME = '/home/papers-help'

PATHS = [
    '', 'status', 'init', 'config', 'migrate', 'install', 'uninstall', 'add', 'check', 'file',
    'file rename', 'file mv', 'file attach', 'file fetch', 'file detach', 'file rm', 'file check', 'file fix',
    'file clean', 'file checksum', 'filecheck', 'list', 'edit', 'rm', 'tag', 'pull', 'push', 'sync',
    'export', 'open', 'doi', 'fetch', 'extract', 'undo', 'redo', 'restore', 'restore-backup', 'git',
    'history', 'backup',
]


def run(path):
    with tempfile.TemporaryDirectory() as cwd:
        env = {'PATH': os.environ['PATH'], 'HOME': HOME, 'LC_ALL': 'C.UTF-8'}
        result = subprocess.run([PAPERS, *path.split(), '-h'], cwd=cwd, env=env, capture_output=True, text=True)
        assert result.returncode == 0 and not result.stderr, (path, result)
        return result.stdout


def python_of(papers):
    "the Python of the papers executable (its shebang)"
    path = shutil.which(papers) or papers
    with open(path) as f:
        first = f.readline()
    return first[2:].strip() if first.startswith('#!') else sys.executable


LINUX = """import sys
sys.platform = 'linux'
sys.argv = ['papers'] + sys.argv[1:]
from papers.cli import main
main()
"""


def run_linux(path):
    "the help as papers prints it on Linux: its paths come from platformdirs, chosen by sys.platform"
    with tempfile.TemporaryDirectory() as cwd:
        env = {'PATH': os.environ['PATH'], 'HOME': HOME, 'LC_ALL': 'C.UTF-8'}
        result = subprocess.run([python_of(PAPERS), '-c', LINUX, *path.split(), '-h'], cwd=cwd, env=env,
                                capture_output=True, text=True)
        assert result.returncode == 0 and not result.stderr, (path, result)
        return result.stdout


def raw(text):
    hashes = '#'
    while '"' + hashes in text:
        hashes += '#'
    return f'r{hashes}"{text}"{hashes}'


# the help in a library, with a global configuration that sets formats: its values and its text
LIB = os.path.realpath('/tmp') + '/papers-help-lib'
LIBHOME = os.path.realpath('/tmp') + '/papers-help-home'
CONFIGURED = ['init', 'add', 'rm', 'config', 'file attach', 'check', 'list', 'file rename', 'extract']


def configured():
    for d in (LIB, LIBHOME):
        shutil.rmtree(d, ignore_errors=True)
    os.makedirs(LIB)
    machine = os.path.join(LIBHOME, 'Library', 'Application Support', 'papers')
    os.makedirs(machine)
    with open(os.path.join(machine, 'config.json'), 'w') as f:
        json.dump({'version': 3, 'paths': 'absolute', 'nameformat': {'template': '{title}-{year}', 'author_num': 5,
                                                                      'author_sep': '+', 'unknown_strict': True},
                   'keyformat': {'template': '{year}', 'title_sep': ' - ', 'title_length': 20}}, f)
    env = {'PATH': os.environ['PATH'], 'HOME': LIBHOME, 'LC_ALL': 'C.UTF-8'}
    subprocess.run([PAPERS, 'init', '--bibtex', 'library.bib', '--filesdir', 'pdfs'], cwd=LIB, env=env, check=True,
                   capture_output=True)
    listing = subprocess.run([PAPERS, 'config'], cwd=LIB, env=env, check=True, capture_output=True, text=True).stdout
    settings = {}
    for line in listing.splitlines()[1:]:
        name, value = line.split(' = ', 1)
        value = value.rsplit('  (', 1)[0]
        if name.strip().endswith('unknown-strict'):
            value = {'true': 'True', 'false': 'False'}[value]
        settings[name.strip()] = value
    values = dict(filesdir=settings.pop('filesdir'), bibtex=settings.pop('bibtex'),
                  machine_config=os.path.join(machine, 'config.json'), paths=settings['paths'],
                  settings={k: v for k, v in settings.items() if k.startswith(('name.', 'key.'))})
    cases = []
    for path in CONFIGURED:
        result = subprocess.run([PAPERS, *path.split(), '-h'], cwd=LIB, env=env, capture_output=True, text=True)
        assert result.returncode == 0 and not result.stderr, (path, result)
        cases.append(dict(path=path, text=result.stdout))
    for d in (LIB, LIBHOME):
        shutil.rmtree(d)
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, '..', 'fixtures', 'help.json'), 'w') as f:
        json.dump(dict(values=values, cases=cases), f, indent=1)
        f.write('\n')


def main():
    configured()
    out = ['// Generated by tests/record/record_help.py from the help of papers-cli: do not edit.', '',
           '/// `(command, usage, help)`: the usage and the help of each command of papers (`file rename` for a',
           '/// subcommand, empty for papers itself), as papers prints them outside of any library.',
           'pub static HELP: &[(&str, &str, &str)] = &[']
    for path in PATHS:
        text = run(path)
        usage = text.split('\n\n', 1)[0] + '\n'
        out.append(f'    ("{path}", {raw(usage)}, {raw(text)}),')
    out.append('];')
    here = os.path.dirname(os.path.abspath(__file__))
    target = os.path.join(here, '..', '..', 'src', 'help_text.rs')
    with open(target, 'w') as f:
        f.write('\n'.join(out) + '\n')
    # for the tests on Linux: the help that differs there (the path of the global configuration)
    linux = ['// Generated by tests/record/record_help.py from the help of papers-cli on Linux: do not edit.', '',
             '/// `(command, help)`: the help of the commands whose help differs on Linux (the path of the global',
             '/// configuration), as papers prints it there.', 'pub static HELP_LINUX: &[(&str, &str)] = &[']
    for path in PATHS:
        text, on_linux = run(path), run_linux(path)
        if on_linux != text:
            linux.append(f'    ("{path}", {raw(on_linux)}),')
    linux.append('];')
    with open(os.path.join(here, '..', 'fixtures', 'help_linux.rs'), 'w') as f:
        f.write('\n'.join(linux) + '\n')


main()
