def repl_expr(fn):
    code = fn.__code__
    key = (code.co_firstlineno, fn.__name__)
    if key == (70, 'formatter'):
        return 'DefaultFn::MathStyle(%s)' % rs_str(fn.__defaults__[0])
    if key == (1573, '<lambda>'):
        return 'DefaultFn::Accent(%s)' % rs_str(fn.__defaults__[0])
    if key == (301, '<lambda>'):
        return 'DefaultFn::Placeholder(%s)' % rs_str(fn.__defaults__[0])
    return 'DefaultFn::%s' % LINE_FNS[key]


def spec_row(name, s, kind):
    r = s.simplify_repl
    if r is None:
        rr = 'DefaultRepl::None'
    elif kind == 'macros' and name == 'today':
        rr = 'DefaultRepl::Today'  # _latex_today(): the date of the day, not a constant
    elif callable(r):
        rr = 'DefaultRepl::Fn(%s)' % repl_expr(r)
    else:
        assert isinstance(r, str)
        rr = 'DefaultRepl::Str(%s)' % rs_str(r)
    if kind == 'specials':
        assert not hasattr(s, 'discard')
        return '            (%s, %s, DISCARD_UNSET),\n' % (rs_str(name), rr)
    d = {True: 'DISCARD_TRUE', False: 'DISCARD_FALSE'}[s.discard]
    return '            (%s, %s, %s),\n' % (rs_str(name), rr, d)


def gen_latex2text():
    db = latex2text.get_default_latex_context_db()
    out = [HEADER]
    out.append('//! `pylatexenc.latex2text.get_default_latex_context_db()` as data.\n\n')
    out.append('use super::{DefaultFn, DefaultRepl, DISCARD_FALSE, DISCARD_TRUE, DISCARD_UNSET};\n\n')
    out.append('/// `(name, simplify_repl, discard)`\n')
    out.append('pub(crate) type Row = (&\'static str, DefaultRepl, u8);\n')
    out.append('/// `(category, macros, environments, specials)`\n')
    out.append('pub(crate) type CategoryRows = (&\'static str, &\'static [Row], &\'static [Row], &\'static [Row]);\n\n')
    out.append('pub(crate) static CATEGORIES: &[CategoryRows] = &[\n')
    for cat in db.category_list:
        d = db.d[cat]
        out.append('    (\n        %s,\n' % rs_str(cat))
        for kind in ('macros', 'environments', 'specials'):
            out.append('        &[\n')
            for name, s in d[kind].items():
                out.append(spec_row(name, s, kind))
            out.append('        ],\n')
        out.append('    ),\n')
    out.append('];\n')
    write('latex2text/defaultspecs.rs', ''.join(out))


# ----------------------------------------------------------------------------- latexencode


def gen_uni2latex(table, fname, what):
    out = [HEADER]
    out.append('//! %s, sorted by code point.\n//!\n' % what)
    out.append('//! Adapted from latexcodec 0.2 by Peter Troeger / Matthias C. M. Troffaes\n'
               '//! (MIT); see the LICENSE file of this crate.\n\n')
    out.append('pub(crate) static TABLE: &[(u32, &str)] = &[\n')
    for k in sorted(table):
        out.append('    (0x%X, %s),\n' % (k, rs_str(table[k])))
    out.append('];\n')
    write(fname, ''.join(out))


if __name__ == '__main__':
    gen_pystr()
    gen_walker()
    gen_latex2text()
