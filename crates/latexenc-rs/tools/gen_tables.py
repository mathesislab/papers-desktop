#!/usr/bin/env python3
"""Generate the data tables of latexenc-rs from the reference, pylatexenc 2.11.

Writes (all marked `@generated`):

  src/pystr_tables.rs                    Python's str.isspace/isalpha/isalnum/isdecimal and the regex \\w class
  src/latexwalker/defaultspecs.rs        latexwalker.get_default_latex_context_db()
  src/latex2text/defaultspecs.rs         latex2text.get_default_latex_context_db()
  src/latexencode/uni2latexmap.rs        latexencode's 'defaults' rule table
  src/latexencode/uni2latexmap_xml.rs    latexencode's 'unicode-xml' rule table

Run with the python that has pylatexenc 2.11 installed, from anywhere:

    /path/to/python3 tools/gen_tables.py
"""
import os
import sys
import unicodedata

import pylatexenc
from pylatexenc import latex2text, latexwalker, macrospec
from pylatexenc.latexencode import _uni2latexmap, _uni2latexmap_xml

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'src')

assert pylatexenc.__version__ == '2.11', pylatexenc.__version__

HEADER = ('// @generated by tools/gen_tables.py from pylatexenc %s (Python %s, Unicode %s). Do not edit.\n\n'
          % (pylatexenc.__version__, '.'.join(map(str, sys.version_info[:3])), unicodedata.unidata_version))


def rs_str(s):
    out = ['"']
    for c in s:
        o = ord(c)
        if c == '"':
            out.append('\\"')
        elif c == '\\':
            out.append('\\\\')
        elif 32 <= o < 127:
            out.append(c)
        else:
            out.append('\\u{%X}' % o)
    out.append('"')
    return ''.join(out)


def write(path, text):
    full = os.path.join(SRC, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, 'w', encoding='utf-8') as f:
        f.write(text)
    print('wrote', os.path.normpath(full), len(text.splitlines()), 'lines')


# ----------------------------------------------------------------------------- pystr


def ranges(pred):
    res = []
    start = None
    for i in range(0x110000):
        if pred(chr(i)):
            if start is None:
                start = i
        elif start is not None:
            res.append((start, i - 1))
            start = None
    if start is not None:
        res.append((start, 0x10FFFF))
    return res


def gen_pystr():
    out = [HEADER]
    out.append('//! Character-class tables of Python `str` (what `str.isspace()`, `str.isalpha()`,\n'
               '//! `str.isalnum()` and the regex `\\w` of `re` use), as inclusive ranges.\n\n')
    tables = [
        ('SPACE', lambda c: c.isspace()),
        ('ALPHA', lambda c: c.isalpha()),
        ('ALNUM', lambda c: c.isalnum()),
        ('WORD', lambda c: c.isalnum() or c == '_'),
        ('DECIMAL', lambda c: c.isdecimal()),
    ]
    for name, pred in tables:
        rs = ranges(pred)
        out.append('pub(crate) static %s: &[(u32, u32)] = &[\n' % name)
        for a, b in rs:
            out.append('    (0x%X, 0x%X),\n' % (a, b))
        out.append('];\n\n')
    write('pystr_tables.rs', ''.join(out))


# ----------------------------------------------------------------------------- latexwalker


def parser_row(p):
    """(argspec, flags, args_math_mode string) of an args parser"""
    if isinstance(p, macrospec.VerbatimArgsParser):
        kind = {'verb-macro': 2, 'verbatim-environment': 4}[p.verbatim_arg_type]
        return ('{', kind, '')
    assert type(p) is macrospec.MacroStandardArgsParser, p
    flags = 1 if p.optional_arg_no_space else 0
    amm = ''
    if p.args_math_mode is not None:
        assert len(p.args_math_mode) == len(p.argspec) and p.argspec
        amm = ''.join({None: 'N', True: 'T', False: 'F'}[x] for x in p.args_math_mode)
    assert not p._like_pylatexenc1x_ignore_leading_star
    return (p.argspec, flags, amm)


def gen_walker():
    db = latexwalker.get_default_latex_context_db()
    out = [HEADER]
    out.append('//! `pylatexenc.latexwalker.get_default_latex_context_db()` as data.\n\n')
    out.append('/// `(macroname, argspec, flags, args_math_mode)`; flags: 1 = `optional_arg_no_space`,\n'
               '/// 2 = `VerbatimArgsParser(\'verb-macro\')`, 4 = `VerbatimArgsParser(\'verbatim-environment\')`;\n'
               '/// `args_math_mode` has one of `T`, `F`, `N` (None) per argument, or is empty (None).\n')
    out.append('pub(crate) type MacroRow = (&\'static str, &\'static str, u8, &\'static str);\n')
    out.append('/// `(environmentname, argspec, flags, args_math_mode, is_math_mode)`\n')
    out.append('pub(crate) type EnvRow = (&\'static str, &\'static str, u8, &\'static str, bool);\n')
    out.append('/// `(category, macros, environments, specials)`\n')
    out.append('pub(crate) type CategoryRows = (\n    &\'static str,\n    &\'static [MacroRow],\n'
               '    &\'static [EnvRow],\n    &\'static [&\'static str],\n);\n\n')
    out.append('pub(crate) static CATEGORIES: &[CategoryRows] = &[\n')
    for cat in db.category_list:
        d = db.d[cat]
        out.append('    (\n        %s,\n        &[\n' % rs_str(cat))
        for name, m in d['macros'].items():
            assert type(m) is macrospec.MacroSpec and m.macroname == name
            a, f, amm = parser_row(m.args_parser)
            out.append('            (%s, %s, %d, %s),\n' % (rs_str(name), rs_str(a), f, rs_str(amm)))
        out.append('        ],\n        &[\n')
        for name, e in d['environments'].items():
            assert type(e) is macrospec.EnvironmentSpec and e.environmentname == name
            a, f, amm = parser_row(e.args_parser)
            out.append('            (%s, %s, %d, %s, %s),\n' % (rs_str(name), rs_str(a), f, rs_str(amm),
                                                              'true' if e.is_math_mode else 'false'))
        out.append('        ],\n        &[\n')
        for name, s in d['specials'].items():
            assert type(s) is macrospec.SpecialsSpec and s.args_parser is None and s.specials_chars == name
            out.append('            %s,\n' % rs_str(name))
        out.append('        ],\n    ),\n')
    out.append('];\n')
    write('latexwalker/defaultspecs.rs', ''.join(out))


